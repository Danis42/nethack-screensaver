"""Write autoascend/combat/monster_data.py from NetHack 3.6.6 src/monst.c.

NLE's permonst has level, speed and AC but no attacks; the bot's threat model needs them.
Usage: uv run python scripts/gen_monster_data.py path/to/monst.c
(https://raw.githubusercontent.com/NetHack/NetHack/NetHack-3.6.6_Released/src/monst.c)"""
import re
