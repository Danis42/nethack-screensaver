ATTK = re.compile(r"ATTK\((\w+),\s*(\w+),\s*(\d+),\s*(\d+)\)")
DISABLED = re.compile(r"^#if 0\b.*?^#endif[^\n]*$", re.S | re.M)


def parse(text):
    """[(name, attacks)] for every MON(...) entry outside `#if 0` blocks, in file order."""
    out = []
    for chunk in DISABLED.sub("", text).split('MON("')[1:]:
        name = chunk[:chunk.index('"')]
        body = chunk[:chunk.index("SIZ(")]
        out.append((name, tuple((AT[a], AD[d], int(n), int(s)) for a, d, n, s in ATTK.findall(body))))
    return out


def align(parsed, names):
    """The parsed entries in the order of `names` (NLE's monster indices); entries NLE lacks are skipped."""
    out, j = [], 0
    for i, name in enumerate(names):
        while j < len(parsed) and parsed[j][0] != name:
            j += 1
        if j == len(parsed):
            raise SystemExit(f"monster {i} {name!r} not found in monst.c order")
        out.append(parsed[j])
        j += 1
    return out


def main(path):
    import nle.nethack as nh
    names = [nh.permonst(i).mname for i in range(nh.NUMMONS)]
    table = align(parse(Path(path).read_text()), names)
    lines = ['"""Generated by scripts/gen_monster_data.py from NetHack 3.6.6 src/monst.c; do not edit.',
             "",
             "Monster data from NetHack, distributed under the NetHack General Public License.",
             'Index = NLE monster index; each entry: (name, ((aatyp, adtyp, damn, damd), ...))."""',
             "MONSTERS = ("]
    lines += [f"    ({name!r}, {attacks!r})," for name, attacks in table]
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(table)} monsters)")


if __name__ == "__main__":
    main(sys.argv[1])
